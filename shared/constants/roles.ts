export function getPermissionsForRole(role: UserRole): PermissionCode[] {
  return ROLE_PERMISSIONS_MATRIX[role] || [];
}

export function roleHasPermission(role: UserRole, permission: PermissionCode | string): boolean {
  if (role === 'SUPER_ADMIN') return true;
  const permissions = ROLE_PERMISSIONS_MATRIX[role];
  return permissions ? permissions.includes(permission as PermissionCode) : false;
}
